// Generates the typed Gleam data modules from data/metro/*.json so the planner and the guide share one source.
//   node scripts/metro-gleam-data.mjs           writes metro/src/peakpune_metro/{ids,data}.gleam
//   node scripts/metro-gleam-data.mjs --check   exits 1 if the committed files are stale
// Station ids become constructors of a custom type, so a reference to an unknown station is a compile error.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildModel, loadMetro, validateMetro, validateAreas } from './metro-model.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'metro/src/peakpune_metro');
const DISPLAY = { 'shivaji-nagar-pink': 'Shivaji Nagar (Line 3)' };

export const pascal = (id) => id.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const gs = (s) => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n') + '"';
const bool = (b) => (b ? 'True' : 'False');
const LINE_CTOR = { purple: 'Purple', aqua: 'Aqua', pink_line3: 'PinkLine3' };

export function renderIds(model) {
  const ids = model.stations.map((s) => s.id);
  const ctors = ids.map(pascal);
  if (new Set(ctors).size !== ctors.length) throw new Error('station constructor names collide');
  const name = (s) => DISPLAY[s.id] || s.names[0];
  return `// GENERATED by scripts/metro-gleam-data.mjs from data/metro/metro.json. Do not edit by hand.

/// Every station the planner knows about. Referring to a station that is not here is a compile error.
pub type StationId {
${ctors.map((c) => '  ' + c).join('\n')}
}

pub type LineId {
  Purple
  Aqua
  PinkLine3
}

pub fn all_stations() -> List(StationId) {
  [${ctors.join(', ')}]
}

pub fn station_to_string(id: StationId) -> String {
  case id {
${ids.map((id, i) => `    ${ctors[i]} -> ${gs(id)}`).join('\n')}
  }
}

pub fn station_from_string(value: String) -> Result(StationId, Nil) {
  case value {
${ids.map((id, i) => `    ${gs(id)} -> Ok(${ctors[i]})`).join('\n')}
    _ -> Error(Nil)
  }
}

pub fn station_name(id: StationId) -> String {
  case id {
${model.stations.map((s, i) => `    ${ctors[i]} -> ${gs(name(s))}`).join('\n')}
  }
}

pub fn line_to_string(id: LineId) -> String {
  case id {
    Purple -> "purple"
    Aqua -> "aqua"
    PinkLine3 -> "pink_line3"
  }
}
`;
}

export function renderData(data, model, areas) {
  const C = (id) => pascal(id);
  const state = { open: 'Open', not_open: 'NotOpen', closed: 'Closed' };
  const lineCode = (l) => LINE_CTOR[l.id];
  const op = (o) => (o === 'maha_metro' ? 'MahaMetro' : 'PitCmrl');
  const lines = model.lines.map((l) => {
    const stops = l.order.map((id) => {
      const m = model.membership[`${l.id}:${id}`];
      return `        Stop(station: ${C(id)}, status: Status(state: ${state[m.state]}, source: ${m.statusSource === 'operator' ? 'OperatorSource' : 'MediaSource'}, verified: ${bool(m.verified)}, as_of: ${gs(m.asOf)}))`;
    }).join(',\n');
    return `    Line(
      id: ${lineCode(l)},
      name: ${gs(l.name)},
      operator: ${op(l.operator)},
      first_terminus: ${gs(l.termini[0])},
      last_terminus: ${gs(l.termini[1])},
      stops: [
${stops},
      ],
    )`;
  }).join(',\n');
  // Maha table: one row per station (District Court once); the duplicate column in the chart only differs at disputed pairs.
  const seen = new Set(); const keep = [];
  model.mahaIds.forEach((id, i) => { if (!seen.has(id)) { seen.add(id); keep.push(i); } });
  const mahaOrder = keep.map((i) => C(model.mahaIds[i]));
  const mahaRows = keep.map((i) => `      [${keep.map((j) => model.mahaMatrix[i][j]).join(', ')}]`).join(',\n');
  const pinkRows = model.pinkMatrix.map((r) => `      [${r.join(', ')}]`).join(',\n');
  const disputed = model.disputed.map((p) => `    #(${C(p.a)}, ${C(p.b)})`).join(',\n');
  const areaSrc = areas.areas.map((a) => `    Area(
      id: ${gs(a.id)},
      name: ${gs(a.name)},
      note: ${gs(a.note)},
      has_station: ${bool(a.has_station)},
      stations: [${a.stations.map((s) => C(s.id)).join(', ')}],
    )`).join(',\n');
  return `// GENERATED by scripts/metro-gleam-data.mjs from data/metro/metro.json and areas.json. Do not edit by hand.
// verified_on and every status below come from the dataset; nothing here is typed in by hand.

import gleam/option.{None, Some}
import peakpune_metro/ids.{
${[...model.stations.map((s) => C(s.id)), 'Aqua', 'PinkLine3', 'Purple'].map((c) => '  ' + c).join(',\n')},
}
import peakpune_metro/types.{
  Area, Closed, FareTable, Line, MahaMetro, MediaSource, Network, NotOpen, Open,
  OperatorSource, PitCmrl, Status, Stop,
}

pub fn network() -> types.Network {
  Network(
    verified_on: ${gs(data.verified_on)},
    lines: [
${lines},
    ],
    maha_fares: FareTable(
      order: [${mahaOrder.join(', ')}],
      rows: [
${mahaRows},
      ],
    ),
    pink_fares: FareTable(
      order: [${model.pinkIds.map(C).join(', ')}],
      rows: [
${pinkRows},
      ],
    ),
    disputed: [
${disputed},
    ],
    areas: [
${areaSrc},
    ],
    maha_whatsapp: Some(${gs(data.operators.maha_metro.whatsapp_eticket)}),
    pink_whatsapp: ${data.operators.pitcmrl.whatsapp_eticket ? `Some(${gs(data.operators.pitcmrl.whatsapp_eticket)})` : 'None'},
    maha_fare_chart_url: ${gs(data.provenance.mahametro_fare_chart_page)},
    pink_fare_chart_url: ${gs(data.provenance.line3_fare_table_page)},
  )
}
`;
}

export function generate() {
  const data = loadMetro();
  const areas = JSON.parse(readFileSync(join(root, 'data/metro/areas.json'), 'utf8'));
  const errs = [...validateMetro(data), ...validateAreas(areas, data)];
  if (errs.length) throw new Error('metro data invalid:\n - ' + errs.join('\n - '));
  const model = buildModel(data);
  return { 'ids.gleam': renderIds(model), 'data.gleam': renderData(data, model, areas) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = generate();
  if (process.argv.includes('--check')) {
    const stale = Object.keys(files).filter((f) => { try { return readFileSync(join(OUT, f), 'utf8') !== files[f]; } catch { return true; } });
    if (stale.length) { console.error('Generated Gleam data is stale: ' + stale.join(', ') + '. Run: node scripts/metro-gleam-data.mjs'); process.exit(1); }
    console.log('generated Gleam data is current');
  } else {
    mkdirSync(OUT, { recursive: true });
    for (const [f, text] of Object.entries(files)) writeFileSync(join(OUT, f), text);
    console.log('wrote ' + Object.keys(files).map((f) => `metro/src/peakpune_metro/${f}`).join(', '));
  }
}
